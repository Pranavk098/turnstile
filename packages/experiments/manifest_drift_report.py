"""Manifest-vs-adjudication drift report (batch 2 T5) -- READ-ONLY.

Compares every golden fixture's ``manifest.yaml`` expected_verdict against
what ``adjudicate()`` returns TODAY, and writes the diff to
``docs/superpowers/manifest-drift-report.md``. This script never writes to
``fixtures/golden/`` -- applying the drift (updating the manifest's expected
verdicts) is the OWNER's one-commit decision; this report is only the diff
the owner applies.

Usage (from the repository root)::

    uv run python packages/experiments/manifest_drift_report.py
"""
from __future__ import annotations

import datetime as _dt
from pathlib import Path

import yaml

from turnstile_schema import load_rates, load_trace
from turnstile_pricing import price_trace
from turnstile_verdict import adjudicate

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "fixtures" / "golden"
MANIFEST = GOLDEN / "manifest.yaml"
RATES_PATH = ROOT / "pricing" / "rates.yaml"
OUT_PATH = ROOT / "docs" / "superpowers" / "manifest-drift-report.md"


def _drift_rows() -> list[dict]:
    manifest = yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))["fixtures"]
    rates = load_rates(RATES_PATH)
    rows: list[dict] = []
    for entry in manifest:
        fid = entry["id"]
        priced = price_trace(load_trace(GOLDEN / f"{fid}.json"), rates)
        label = adjudicate(priced).label.value
        rows.append({
            "id": fid,
            "manifest": entry["expected_verdict"],
            "adjudicated": label,
            "match": label == entry["expected_verdict"],
        })
    return rows


def main() -> None:
    rows = _drift_rows()
    drifters = [r for r in rows if not r["match"]]
    lines = [
        "# Manifest-vs-adjudication drift report",
        "",
        f"Generated by `packages/experiments/manifest_drift_report.py` "
        f"(`uv run python packages/experiments/manifest_drift_report.py`), "
        f"last run {_dt.datetime.now(_dt.timezone.utc).isoformat(timespec='seconds')}.",
        "",
        "READ-ONLY diff for the owner to apply: for every golden fixture, the "
        "manifest's `expected_verdict` vs what `turnstile_verdict.adjudicate()` "
        "returns today. This report changes NOTHING under `fixtures/golden/` "
        "— applying it (updating the manifest's expectations, one commit) is "
        "owner lane.",
        "",
        f"**{len(drifters)} of {len(rows)} fixtures drift** "
        f"({', '.join(r['id'] for r in drifters) if drifters else 'none'}).",
        "",
        "Context for the two known causes:",
        "",
        "* The manifest's `PARTIALLY_RESOLVED` placeholders predate the "
        "label's first emitter (batch 1 C2's scenario registry) and several "
        "were best-judgment placeholders that never matched adjudication "
        "(per test_adjudicate.py's PINNED-vs-placeholder split).",
        "* Adjudication itself changed in batch 1 (non-clean-end guard, "
        "intent-bound FALSE_RESOLVE, registry labels) and the baselines were "
        "recalibrated -- the `adjudicated` column is today's ledger, "
        "warts included.",
        "",
        "| Fixture | Manifest expected | Adjudicated today | Match? |",
        "|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['id']} | {r['manifest']} | {r['adjudicated']} "
            f"| {'yes' if r['match'] else '**NO**'} |"
        )
    lines += [
        "",
        "## Owner application notes",
        "",
        "* Update `expected_verdict` in `fixtures/golden/manifest.yaml` to the "
        "`Adjudicated today` column for every row flagged **NO** (or fix the "
        "fixture if the LEDGER is wrong -- each drift is a claim to review, "
        "not a number to rubber-stamp).",
        "* After applying, `packages/verdict/tests/test_adjudicate.py`'s "
        "placeholder sweep becomes a full spec-pin: consider promoting every "
        "fixture to the `PINNED` set so future drift fails loudly.",
        "",
    ]
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_PATH}")
    print(f"{len(drifters)} of {len(rows)} fixtures drift:")
    for r in drifters:
        print(f"  {r['id']:26s} manifest={r['manifest']:20s} adjudicated={r['adjudicated']}")


if __name__ == "__main__":
    main()
